const ACTIVE_CARD_FILES = ["context.md", "trace.md", "benchmarks.md"] as const;
const BACKLOG_CARD_FILES = ["context.md"] as const;

function renderCardFile(fname: string, mapping: CardTemplateMapping): string {
  switch (fname) {
    case "context.md":
      return substitute(CONTEXT_TEMPLATE, mapping);
    case "trace.md":
      return traceTemplate(mapping);
    case "benchmarks.md":
      return benchmarksTemplate(mapping);
    default:
      throw new Error(`unknown card template: ${fname}`);
  }
}

// ─── Card lifecycle ──────────────────────────────────────────────────────────

export type CardState = "backlog" | "active" | "done" | "archive";
export type CardSource = "ado" | "qa" | "prod" | "other";

const LIFECYCLE_STATES: readonly CardState[] = ["backlog", "active", "done", "archive"];

export interface FoundCard {
  state: CardState;
  dir: string;
}

/** Locate a card across backlog/active/done/archive. Returns null if absent. */
export function findCard(cardId: string, root: string = memoryRoot()): FoundCard | null {
  const normalized = sanitizeCardId(cardId);
  for (const state of LIFECYCLE_STATES) {
    const dir = join(root, "issues", state, normalized);
    if (existsSync(dir)) {
      return { state, dir };
    }
  }
  return null;
}

/**
 * List the card IDs currently under `issues/active/` (directory names only —
 * stray files are ignored). Used by callers that need to know how many
 * investigations are in flight without loading each card's content, e.g. the
 * harness plugin's best-effort auto-trace-on-failure hook only wants to act
 * when there is exactly one unambiguous active card to attribute a task
 * failure to. Returns an empty array if `issues/active/` doesn't exist yet
 * (corpus never scaffolded, or scaffolded but no card ever activated).
 */
export function listActiveCards(root: string = memoryRoot()): string[] {
  const activeDir = join(root, "issues", "active");
  if (!existsSync(activeDir)) {
    return [];
  }
  return readdirSync(activeDir).filter((name) => statSync(join(activeDir, name)).isDirectory());
}

export interface CreateCardOptions {
  cardId: string;
  symptom?: string;
  source?: CardSource;
  backlog?: boolean;
  date?: string;
}

/**
 * Scaffold a new investigation card. Active cards (default) get
 * context.md + trace.md + benchmarks.md + artifacts/.gitkeep. Backlog cards
 * (`backlog: true`) get context.md only. Refuses if the card already exists
 * in any lifecycle directory. Atomic: all file contents are rendered before
 * any directory is created; a partially-written card is rolled back on
 * failure. Returns the list of files created (relative to the card dir).
 */
export function createCard(opts: CreateCardOptions, root: string = memoryRoot()): string[] {
  scaffoldCorpus(root);

  const cardId = sanitizeCardId(opts.cardId);
  const backlog = opts.backlog ?? false;
  const source = opts.source ?? "other";
  const date = opts.date ?? todayIso();
  const symptom = opts.symptom ?? "";

  if (!backlog && !symptom.trim()) {
    throw new Error("createCard: symptom is required for active cards (omit only with backlog: true)");
  }

  const existing = findCard(cardId, root);
  if (existing) {
    throw new Error(`createCard: card already exists: ${existing.dir} (refusing to overwrite)`);
  }

  const state: CardState = backlog ? "backlog" : "active";
  const cardDir = join(root, "issues", state, cardId);
  const mapping: CardTemplateMapping = { CARD_ID: cardId, DATE: date, SOURCE: source, SYMPTOM: symptom };
  const files: readonly string[] = backlog ? BACKLOG_CARD_FILES : ACTIVE_CARD_FILES;

  // Render everything before touching the filesystem so a template problem
  // fails before any directory is created.
  const rendered = new Map<string, string>();
  for (const fname of files) {
    rendered.set(fname, renderCardFile(fname, mapping));
  }

  const written: string[] = [];
  try {
    mkdirSync(cardDir, { recursive: true });
    for (const fname of files) {
      writeFileSync(join(cardDir, fname), rendered.get(fname) as string, "utf8");
      written.push(fname);
    }
    if (!backlog) {
      const artifactsDir = join(cardDir, "artifacts");
      mkdirSync(artifactsDir, { recursive: true });
      writeFileSync(join(artifactsDir, ".gitkeep"), "", "utf8");
      written.push("artifacts/.gitkeep");
    }
  } catch (error) {
    rmSync(cardDir, { recursive: true, force: true });
    throw error;
  }

  return written;
}

// ─── Trace ───────────────────────────────────────────────────────────────────

export type TraceEntryType = "finding" | "ruled-out" | "hypothesis" | "next-step";

export interface AppendTraceOptions {
  cardId: string;
  type: TraceEntryType;
  body: string;
  session?: string;
  date?: string;
}

export interface AppendTraceResult {
  path: string;
  linesBefore: number;
  linesAfter: number;
  bytesBefore: number;
  tokensAvoided: number;
  formatted: string;
}

const CHARS_PER_TOKEN = 4;

function lineCount(path: string): number {
  if (!existsSync(path)) {
    return 0;
  }
  const content = readFileSync(path, "utf8");
  if (content.length === 0) {
    return 0;
  }
  const lines = content.split("\n");
  if (content.endsWith("\n")) {
    lines.pop();
  }
  return lines.length;
}

/**
 * Append one structured entry to an active card's trace.md. Refuses if the
 * card exists but is not in `issues/active/` (naming the actual state), or
 * if the card cannot be found at all. Append-only: never reads and rewrites
 * the body — only `appendFileSync` touches an existing trace.md. If
 * trace.md doesn't exist yet (e.g. just activated from backlog), the
 * standard header is written first.
 */
export function appendTrace(opts: AppendTraceOptions, root: string = memoryRoot()): AppendTraceResult {
  const cardId = sanitizeCardId(opts.cardId);
  const body = opts.body.trim();
  if (!body) {
    throw new Error("appendTrace: empty entry body (body must not be empty or whitespace-only)");
  }

  const found = findCard(cardId, root);
  if (!found) {
    throw new Error(`appendTrace: no active card ${cardId} (looked in ${join(root, "issues", "active", cardId)})`);
  }
  if (found.state !== "active") {
    throw new Error(
      `appendTrace: ${cardId} is in issues/${found.state}/, not active. Traces are for active cards — activate it first (move it to issues/active/).`,
    );
  }

  const tracePath = join(found.dir, "trace.md");
  const session = opts.session ?? "opencode";
  const date = opts.date ?? nowMinuteIso();

  // Bootstrap the header if this card was activated from backlog with no
  // trace.md yet. This is the only write to trace.md that happens before the
  // append-only block below, and it only ever runs when the file is absent.
  if (!existsSync(tracePath)) {
    writeFileSync(tracePath, traceHeader(cardId), "utf8");
  }

  const linesBefore = lineCount(tracePath);
  const bytesBefore = statSync(tracePath).size;

  const block = `\n---\ndate: ${date}\nsession: ${session}\ntype: ${opts.type}\n---\n${body}\n`;
  appendFileSync(tracePath, block, "utf8"); // append-only: never rewrites prior entries

  const linesAfter = lineCount(tracePath);
  const tokensAvoided = Math.round(bytesBefore / CHARS_PER_TOKEN);

  const formatted =
    `Appended ${opts.type} entry to ${tracePath} (${linesBefore} -> ${linesAfter} lines)\n` +
    `  ~${tokensAvoided} tokens not pulled into context (appended without re-reading the trace)`;

  return { path: tracePath, linesBefore, linesAfter, bytesBefore, tokensAvoided, formatted };
}

// ─── Context assembly ────────────────────────────────────────────────────────

export type ContextMode = "compact" | "full";

export interface AssembleContextOptions {
  cardId: string;
  mode?: ContextMode;
  sections?: string[];
}

const SYSTEM_SECTION_ORDER: readonly string[] = SYSTEM_SUBDIRS;

function resolveSections(root: string, requested: string[] | undefined): string[] {
  if (requested && requested.length > 0) {
    return requested;
  }
  return SYSTEM_SECTION_ORDER.filter((name) => {
    const dir = join(root, "system", name);
    return existsSync(dir) && readdirSync(dir).some((f) => f.endsWith(".md"));
  });
}

function headingsOf(content: string): string[] {
  return content
    .split("\n")
    .filter((line) => /^##(?!#)\s*\S/.test(line))
    .map((line) => line.trim());
}

function buildSystemKnowledgeSection(root: string, sections: string[], mode: ContextMode): string {
  if (sections.length === 0) {
    return "_No system/ sections selected, or all selected sections are empty._";
  }

  const blocks: string[] = [];
  if (mode === "compact") {
    blocks.push("_Compact mode — showing headings only. Ask for full content on specific files if needed._");
  }

  for (const section of sections) {
    const dir = join(root, "system", section);
    const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).sort() : [];
    if (files.length === 0) {
      blocks.push(`### ${section}/\n\n_(empty)_`);
      continue;
    }
    for (const file of files) {
      const content = readFileSync(join(dir, file), "utf8");
      if (mode === "full") {
        blocks.push(`### ${section}/${file}\n\n${content.trimEnd()}`);
      } else {
        const headings = headingsOf(content);
        blocks.push(`### ${section}/${file}\n\n${headings.length > 0 ? headings.join("\n") : "_(no headings)_"}`);
      }
    }
  }
  return blocks.join("\n\n");
}

/** Split a trace.md body into its leading header and its `---`-delimited entries. */
function splitTraceEntries(content: string): { header: string; entries: string[] } {
  const marker = /\n---\ndate:/g;
  const indices: number[] = [];
  let m: RegExpExecArray | null;
  while ((m = marker.exec(content)) !== null) {
    indices.push(m.index + 1); // +1 skips the leading \n, so the slice starts at "---"
  }
  if (indices.length === 0) {
    return { header: content, entries: [] };
  }
  const header = content.slice(0, indices[0]);
  const entries: string[] = [];
  for (let i = 0; i < indices.length; i++) {
    const start = indices[i];
    const end = i + 1 < indices.length ? indices[i + 1] : content.length;
    entries.push(content.slice(start, end));
  }
  return { header, entries };
}

function compactTrace(content: string): string {
  const { header, entries } = splitTraceEntries(content);
  if (entries.length === 0) {
    return content;
  }
  const total = entries.length;
  const last10 = entries.slice(-10);
  const note =
    total > 10 ? `_Showing last 10 of ${total} entries. Run in full mode to see all._\n\n` : "";
  return `${header.trimEnd()}\n\n${note}${last10.join("").trimEnd()}\n`;
}

function benchmarksHasEntries(content: string): boolean {
  const withoutComments = content.replace(/<!--[\s\S]*?-->/g, "");
  return /\ndate:\s*\S/.test(withoutComments) || /^date:\s*\S/m.test(withoutComments);
}

/**
 * Assemble a focused markdown context payload for priming a new AI analysis
 * session, pulling from the card (context.md/trace.md/benchmarks.md) and
 * selected `system/` sections.
 */
export function assembleContext(opts: AssembleContextOptions, root: string = memoryRoot()): string {
  const cardId = sanitizeCardId(opts.cardId);
  const mode: ContextMode = opts.mode ?? "compact";
  const found = findCard(cardId, root);
  if (!found) {
    throw new Error(`assembleContext: card not found: ${cardId}`);
  }

  const contextPath = join(found.dir, "context.md");
  const contextSection = existsSync(contextPath)
    ? readFileSync(contextPath, "utf8").trimEnd()
    : "_context.md not found for this card._";

  const tracePath = join(found.dir, "trace.md");
  let traceSection: string;
  if (!existsSync(tracePath)) {
    traceSection = "_trace.md not found for this card (local working state may not be present)._";
  } else {
    const traceContent = readFileSync(tracePath, "utf8");
    traceSection = (mode === "full" ? traceContent : compactTrace(traceContent)).trimEnd();
  }

  const benchmarksPath = join(found.dir, "benchmarks.md");
  const benchmarksContent = existsSync(benchmarksPath) ? readFileSync(benchmarksPath, "utf8") : "";
  const benchmarksSection = benchmarksHasEntries(benchmarksContent)
    ? benchmarksContent.trimEnd()
    : "_No promoted benchmarks logged on this card yet._";

  const sections = resolveSections(root, opts.sections);
  const knowledgeSection = buildSystemKnowledgeSection(root, sections, mode);

  return [
    `# RAG Context — ${cardId}`,
    `_Generated: ${nowMinuteIso()} | Mode: ${mode}_`,
    "",
    "## Active Card Summary",
    "",
    contextSection,
    "",
    "## Investigation History",
    "",
    traceSection,
    "",
    "## Relevant System Knowledge",
    "",
    knowledgeSection,
    "",
    "## Promoted Benchmarks on This Card",
    "",
    benchmarksSection,
    "",
  ].join("\n");
}

// ─── Promotion ───────────────────────────────────────────────────────────────

export interface PromoteFindingOptions {
  cardId: string;
  finding: string;
  impact?: string;
  /** Path relative to system/, e.g. 'known-behaviors/foo.md'. */
  targetPath: string;
  title?: string;
  sectionTitle?: string;
  session?: string;
  date?: string;
}

export interface PromoteFindingResult {
  systemPath: string;
  benchmarksPath: string;
  created: boolean;
}

function validateTargetPath(targetPath: string): string {
  const normalized = targetPath.replace(/\\/g, "/").replace(/^\/+/, "");
  const segments = normalized.split("/");
  if (!normalized || isAbsolute(targetPath) || segments.includes("..") || segments.includes(".")) {
    throw new Error(
      `promoteFinding: invalid targetPath (must be relative, stay under system/, no ".."): ${targetPath}`,
    );
  }
  return normalized;
}

function quoteFrontmatterValue(value: string): string {
  return /[:`]/.test(value) ? JSON.stringify(value) : value;
}

function renderSystemFrontmatter(f: {
  title: string;
  domain: string;
  sourceCards: string[];
  created: string;
  updated: string;
}): string {
  return [
    "---",
    `title: ${quoteFrontmatterValue(f.title)}`,
    `domain: ${f.domain}`,
    `source_cards: [${f.sourceCards.join(", ")}]`,
    `created: ${f.created}`,
    `updated: ${f.updated}`,
    "status: active",
    "format_gen: 3",
    "tags: []",
    "---",
    "",
  ].join("\n");
}

function extractBracketList(line: string): string[] {
  const m = line.match(/\[(.*)\]/);
  if (!m || !m[1].trim()) {
    return [];
  }
  return m[1]
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

/**
 * Update only `source_cards` (dedupe) and `updated` in an existing
 * system/ doc's frontmatter, leaving `format_gen` and every other line
 * untouched, then append a new `## section` at the end of the file.
 */
function appendSystemSection(
  content: string,
  opts: { sectionTitle: string; cardId: string; date: string; finding: string; impact?: string },
): string {
  const fmMatch = content.match(/^---\n([\s\S]*?)\n---\n/);
  let updated = content;

  if (fmMatch) {
    const fmBody = fmMatch[1];
    const newLines = fmBody.split("\n").map((line) => {
      if (line.startsWith("source_cards:")) {
        const ids = extractBracketList(line);
        if (!ids.includes(opts.cardId)) {
          ids.push(opts.cardId);
        }
        return `source_cards: [${ids.join(", ")}]`;
      }
      if (line.startsWith("updated:")) {
        return `updated: ${opts.date}`;
      }
      return line;
    });
    const newFrontmatter = `---\n${newLines.join("\n")}\n---\n`;
    updated = newFrontmatter + content.slice(fmMatch[0].length);
  }

  const impactLine = opts.impact ? `**Impact**: ${opts.impact}\n` : "";
  const section = `\n## ${opts.sectionTitle}\n**Source**: ${opts.cardId} | ${opts.date}\n**Finding**: ${opts.finding}\n${impactLine}`;
  return `${updated.trimEnd()}\n${section}`;
}

/**
 * Promote a confirmed finding from a card to `system/`. Writes a new file
 * with frontmatter (or appends a new `## section` to an existing file,
 * updating only `source_cards`/`updated`), then records a `promoted` entry
 * in the card's benchmarks.md. Never touches trace.md.
 */
export function promoteFinding(opts: PromoteFindingOptions, root: string = memoryRoot()): PromoteFindingResult {
  const cardId = sanitizeCardId(opts.cardId);
  const found = findCard(cardId, root);
  if (!found) {
    throw new Error(`promoteFinding: card not found: ${cardId}`);
  }
  if (found.state === "backlog") {
    throw new Error(
      `promoteFinding: ${cardId} is in issues/backlog/; promote from an active (or done/archive) card`,
    );
  }

  const finding = opts.finding.trim();
  if (!finding) {
    throw new Error("promoteFinding: finding text must not be empty");
  }

  const relTarget = validateTargetPath(opts.targetPath);
  const systemPath = join(root, "system", ...relTarget.split("/"));
  const date = opts.date ?? todayIso();
  const session = opts.session ?? "opencode";
  const sectionTitle = opts.sectionTitle ?? opts.title ?? "Finding";

  const alreadyExists = existsSync(systemPath);
  if (!alreadyExists) {
    mkdirSync(dirname(systemPath), { recursive: true });
    const title = opts.title ?? sectionTitle;
    const domainSegments = relTarget.split("/").slice(0, -1);
    const domain = domainSegments.length > 0 ? domainSegments.join("/") : relTarget;
    const frontmatter = renderSystemFrontmatter({
      title,
      domain,
      sourceCards: [cardId],
      created: date,
      updated: date,
    });
    const impactLine = opts.impact ? `**Impact**: ${opts.impact}\n` : "";
    const body = `# ${title}\n\n## ${sectionTitle}\n**Source**: ${cardId} | ${date}\n**Finding**: ${finding}\n${impactLine}`;
    writeFileSync(systemPath, frontmatter + "\n" + body, "utf8");
  } else {
    const existingContent = readFileSync(systemPath, "utf8");
    const updatedContent = appendSystemSection(existingContent, {
      sectionTitle,
      cardId,
      date,
      finding,
      impact: opts.impact,
    });
    writeFileSync(systemPath, updatedContent, "utf8");
  }

  const benchmarksPath = join(found.dir, "benchmarks.md");
  const entry = `\n---\ndate: ${date}\nsession: ${session}\nfinding: ${finding}\ntarget: system/${relTarget}\nstatus: promoted\n---\n`;
  appendFileSync(benchmarksPath, entry, "utf8"); // never touches trace.md

  return { systemPath, benchmarksPath, created: !alreadyExists };
}
