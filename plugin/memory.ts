// ─── Card id sanitization ───────────────────────────────────────────────────────

// Path separators + characters illegal on Windows/exFAT + control chars.
const UNSAFE_CARD_CHARS = /[<>:"/\\|?*\x00-\x1f]/g;

/**
 * Reduce an arbitrary id to one safe path component with a canonical CARD-
 * prefix. Exact parity with the reference plugin's `normalize_card_name`:
 * strip '#', neutralize path separators / FS-hostile characters, drop
 * pure-dot segments ('.', '..', '...'), collapse whitespace/hyphens, and
 * canonicalize the CARD- prefix (case-insensitive detection, never doubled).
 */
export function sanitizeCardId(raw: string): string {
  const withoutHash = raw.split("#").join("");
  const cleaned = withoutHash.replace(UNSAFE_CARD_CHARS, " ");
  const parts = cleaned
    .split(/\s+/)
    .filter((p) => p.length > 0)
    .filter((p) => p.replace(/^\.+|\.+$/g, "").length > 0);

  let name = parts
    .join("-")
    .replace(/-{2,}/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "");

  if (!name) {
    throw new Error(`card id is empty after sanitization: ${JSON.stringify(raw)}`);
  }

  name = name.toUpperCase().startsWith("CARD-") ? "CARD-" + name.slice(5) : "CARD-" + name;

  if (name.includes("/") || name.includes("\\") || name.includes(sep)) {
    throw new Error(`invalid card id after sanitization: ${JSON.stringify(name)}`);
  }
  return name;
}

// ─── Date helpers ────────────────────────────────────────────────────────────

function pad2(n: number): string {
  return String(n).padStart(2, "0");
}

function todayIso(): string {
  const d = new Date();
  return `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`;
}

function nowMinuteIso(): string {
  const d = new Date();
  return `${todayIso()} ${pad2(d.getHours())}:${pad2(d.getMinutes())}`;
}

