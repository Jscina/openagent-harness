function writeIfMissing(path: string, content: string): void {
  if (!existsSync(path)) {
    writeFileSync(path, content, "utf8");
  }
}

/**
 * Idempotent auto-scaffold: creates the full `.opencode/memory/` directory
 * tree, the corpus `.gitignore` commit boundary, `.rag-meta.json`, and
 * README/BENCHMARKS boilerplate. Never overwrites existing files. Called
 * automatically by `createCard`.
 */
export function scaffoldCorpus(root: string = memoryRoot()): void {
  mkdirSync(root, { recursive: true });
  for (const sub of SYSTEM_SUBDIRS) {
    mkdirSync(join(root, "system", sub), { recursive: true });
  }
  for (const sub of ISSUE_SUBDIRS) {
    mkdirSync(join(root, "issues", sub), { recursive: true });
  }

  writeIfMissing(join(root, ".gitignore"), CORPUS_GITIGNORE);
  writeIfMissing(join(root, ".rag-meta.json"), JSON.stringify(RAG_META, null, 2) + "\n");
  writeIfMissing(join(root, "README.md"), ROOT_README);
  writeIfMissing(join(root, "BENCHMARKS.md"), BENCHMARKS_POLICY);
  writeIfMissing(join(root, "system", "README.md"), SYSTEM_README);
  writeIfMissing(join(root, "issues", "README.md"), ISSUES_README);
}

// ─── Card templates ──────────────────────────────────────────────────────────

type CardTemplateMapping = {
  CARD_ID: string;
  DATE: string;
  SOURCE: string;
  SYMPTOM: string;
};

function substitute(text: string, mapping: CardTemplateMapping): string {
  return text
    .replace(/\{\{CARD_ID\}\}/g, mapping.CARD_ID)
    .replace(/\{\{DATE\}\}/g, mapping.DATE)
    .replace(/\{\{SOURCE\}\}/g, mapping.SOURCE)
    .replace(/\{\{SYMPTOM\}\}/g, mapping.SYMPTOM);
}

